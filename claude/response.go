type ClaudeResponse struct {
	resp    *anthropic.Message
	cot     []brain.Signed
	thought *brain.Signed
	prompt  brain.Signed
	model   string
}

func (r *ClaudeResponse) Prompt() brain.Signed {
	return r.prompt
}

func (r *ClaudeResponse) Source() string {
	return "claude"
}

func candidatesToThoughts(resp *anthropic.Message) []brain.Signed {
	thoughts := []brain.Signed{}
	for _, c := range resp.Content {
		if c.Type == "thinking" || c.Type == "redacted_thinking" { // What is redacted thinking????
			last := len(thoughts) - 1
			if last < 0 {
				thoughts = append(thoughts, brain.NewUnsigned(c.AsThinking().Thinking, "cot"))
			} else {
				thoughts = append(thoughts, thoughts[last].NextUnsigned(c.AsThinking().Thinking))
			}
		}
	}
	return thoughts
}

func (r *ClaudeResponse) CoT() []brain.Signed {
	if r.cot == nil {
		r.cot = candidatesToThoughts(r.resp)
	}
	return r.cot
}

func (r *ClaudeResponse) Text() *brain.Signed {
	if r.thought == nil {
		s := brain.NewUnsigned(extractText(r.resp), "text")
		r.thought = &s
	}
	return r.thought
}

func (r *ClaudeResponse) Sign(sv brain.SignVerifier) error {
	if r.cot == nil {
		_ = r.CoT()
	}
	if r.thought == nil {
		_ = r.Text()
	}
	if r.prompt.Signature == "" {
		err := r.prompt.Sign(sv)
		if err != nil {
			return err
		}
	}
	var err error
	for i := range r.cot {
		err = r.cot[i].Sign(sv)
		if err != nil {
			return err
		}
	}
	err = r.thought.Sign(sv)
	return err
}

func (r *ClaudeResponse) Verify(sv brain.SignVerifier) error {
	if r.cot == nil || r.thought == nil {
		return brain.ErrUnsigned
	}
	var err error
	for i := range r.cot {
		err = r.cot[i].Verify(sv)
		if err != nil {
			return err
		}
	}
	return r.thought.Verify(sv)
}

func (r *ClaudeResponse) IsError() error {
	return nil
}

func objToString(v any) string {
	buffer := &bytes.Buffer{}
	encoder := json.NewEncoder(buffer)
	encoder.SetEscapeHTML(false) // <--- THIS SAVES YOUR CREDITS
	_ = encoder.Encode(v)
	return strings.TrimSpace(buffer.String())
}

