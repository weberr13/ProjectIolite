type GeminiResponse struct {
	resp    *genai.GenerateContentResponse
	cot     []brain.Signed
	thought *brain.Signed
	prompt  brain.Signed
	model   string
}

func (r *GeminiResponse) Prompt() brain.Signed {
	return r.prompt
}

func (r *GeminiResponse) Source() string {
	return "gemini"
}

func candidatesToThoughts(resp *genai.GenerateContentResponse) []brain.Signed {
	thoughts := []brain.Signed{}
	if resp == nil { // Global safety
		return thoughts
	}
	for _, c := range resp.Candidates {
		// Guard against nil candidates or missing content
		if c == nil || c.Content == nil {
			continue
		}
		for _, p := range c.Content.Parts {
			// Guard against nil parts
			if p == nil || !p.Thought {
				continue
			}

			last := len(thoughts) - 1
			if last < 0 {
				thoughts = append(thoughts, brain.NewUnsigned(p.Text, "cot"))
			} else {
				thoughts = append(thoughts, thoughts[last].NextUnsigned(p.Text))
			}
		}
	}
	return thoughts
}

func (r *GeminiResponse) CoT() []brain.Signed {
	if r.cot == nil {
		r.cot = candidatesToThoughts(r.resp)
	}
	return r.cot
}

func (r *GeminiResponse) Text() *brain.Signed {
	if r.thought == nil {
		s := brain.NewUnsigned(r.resp.Text(), "text")
		r.thought = &s
	}
	return r.thought
}

func (r *GeminiResponse) Sign(sv brain.SignVerifier) error {
	if r.cot == nil {
		_ = r.CoT()
	}
	if r.thought == nil {
		_ = r.Text()
	}

	if r.prompt.Signature == "" {
		if err := r.prompt.Sign(sv); err != nil {
			return err
		}
	}

	// 2. Chain the thoughts
	lastSig := "" // TODO: r.prompt.Signature Start with the prompt's signature
	for i := range r.cot {
		r.cot[i].PrevSignature = lastSig // STITCH THE CHAIN
		if err := r.cot[i].Sign(sv); err != nil {
			return err
		}
		lastSig = r.cot[i].Signature
	}

	// 3. Chain the final output to the last thought
	r.thought.PrevSignature = lastSig
	return r.thought.Sign(sv)
}

func (r *GeminiResponse) Verify(sv brain.SignVerifier) error {
	if r.cot == nil || r.thought == nil {
		return brain.ErrUnsigned
	}
	var err error
	for i := range r.cot {
		err = r.cot[i].Verify(sv)
		if err != nil {
			return err
		}
	}
	return r.thought.Verify(sv)
}

func (r *GeminiResponse) IsError() error {
	return nil
}

func objToString(v any) string {
	buffer := &bytes.Buffer{}
	encoder := json.NewEncoder(buffer)
	encoder.SetEscapeHTML(false) // <--- THIS SAVES YOUR CREDITS
	_ = encoder.Encode(v)
	return strings.TrimSpace(buffer.String())
}

